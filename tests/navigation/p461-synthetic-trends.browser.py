import asyncio
from pathlib import Path
from playwright.async_api import async_playwright
S = Path("/tmp/browser/p461/shots"); S.mkdir(parents=True, exist_ok=True)
URL = "http://localhost:8080/mission/companion"
async def run(p, w, h, tag):
    b = await p.chromium.launch(headless=True)
    ctx = await b.new_context(viewport={"width": w, "height": h})
    page = await ctx.new_page()
    errs = []; page.on("pageerror", lambda e: errs.append(str(e)))
    reqs = []; page.on("request", lambda r: reqs.append(r.url))
    await page.goto(URL, wait_until="networkidle")
    sec = page.get_by_role("region", name="Synthetic trend demonstration")
    await sec.wait_for()
    btn = sec.get_by_role("button", name="Show synthetic example")
    print(tag, "trend status:", await page.get_by_test_id("trend-status").inner_text())
    print(tag, "hidden by default:", await page.get_by_test_id("companion-synthetic-trend").count() == 0, "aria-expanded:", await btn.get_attribute("aria-expanded"))
    before = len(reqs)
    await btn.click()
    chart = page.get_by_test_id("companion-synthetic-trend")
    print(tag, "shown:", await chart.count(), "aria-expanded:", await sec.get_by_role("button", name="Hide synthetic example").get_attribute("aria-expanded"))
    print(tag, "label:", await chart.get_by_text("SYNTHETIC DEMONSTRATION").count())
    print(tag, "svg aria:", await chart.get_by_role("img").get_attribute("aria-label"))
    print(tag, "circles:", await chart.locator("circle").count())
    await page.wait_for_timeout(300)
    print(tag, "network requests on toggle:", reqs[before:])
    ov = await page.evaluate("document.documentElement.scrollWidth - window.innerWidth"); print(tag, "horizontal overflow px:", ov)
    await sec.scroll_into_view_if_needed(); await sec.screenshot(path=str(S / f"{tag}_shown.png"))
    ls = await page.evaluate("JSON.stringify(Object.assign({}, localStorage)) + JSON.stringify(Object.assign({}, sessionStorage))")
    print(tag, "storage has synthetic values:", "68, 70" in ls or "synthetic-trend" in ls.lower())
    await sec.get_by_role("button", name="Hide synthetic example").click()
    print(tag, "hidden again:", await page.get_by_test_id("companion-synthetic-trend").count() == 0)
    await sec.get_by_role("button", name="Show synthetic example").focus()
    await page.keyboard.press("Enter")
    print(tag, "keyboard toggle shows:", await page.get_by_test_id("companion-synthetic-trend").count())
    await page.reload(wait_until="networkidle")
    print(tag, "after reload hidden:", await page.get_by_test_id("companion-synthetic-trend").count() == 0)
    print(tag, "page errors:", errs)
    await b.close()
async def main():
    async with async_playwright() as p:
        await run(p, 1280, 1800, "desktop")
        await run(p, 390, 844, "mobile")
asyncio.run(main())
