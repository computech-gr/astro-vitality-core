import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

function command(name, args, options = {}) {
  return execFileSync(name, args, { encoding: "utf8", stdio: options.capture ? ["ignore", "pipe", "pipe"] : "inherit" });
}

function requireCommand(name, versionArgs = ["--version"]) {
  try {
    execFileSync(name, versionArgs, { stdio: "ignore" });
  } catch {
    console.error(`Missing required command: ${name}`);
    process.exit(1);
  }
}

function parseEnv(text) {
  const env = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#") || !line.includes("=")) continue;
    const index = line.indexOf("=");
    const key = line.slice(0, index).trim();
    let value = line.slice(index + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  }
  return env;
}

requireCommand("docker");
requireCommand("supabase");

console.log("Starting local Supabase...");
command("supabase", ["start"]);
console.log("Resetting local database from repository migrations and seed...");
command("supabase", ["db", "reset", "--local"]);

const statusText = command("supabase", ["status", "-o", "env"], { capture: true });
const local = parseEnv(statusText);
const apiUrl = local.API_URL;
const publishableKey = local.ANON_KEY || local.PUBLISHABLE_KEY;

if (!apiUrl || !publishableKey) {
  console.error("Could not derive API_URL and ANON_KEY/PUBLISHABLE_KEY from `supabase status -o env`.");
  process.exit(1);
}

const lines = [
  "# Generated by scripts/setup-local.mjs. Local development only. Do not commit.",
  "VITE_SUPABASE_PROJECT_ID=local",
  `VITE_SUPABASE_URL=${apiUrl}`,
  `VITE_SUPABASE_PUBLISHABLE_KEY=${publishableKey}`,
  "SUPABASE_PROJECT_ID=local",
  `SUPABASE_URL=${apiUrl}`,
  `SUPABASE_PUBLISHABLE_KEY=${publishableKey}`,
  "VITE_SITE_ORIGIN=http://localhost:3000",
  "",
];

writeFileSync(".env.local", lines.join("\n"), { mode: 0o600 });
console.log("Local Supabase is ready. Browser-safe configuration written to .env.local.");
console.log("The service-role key was not written to the application environment.");
